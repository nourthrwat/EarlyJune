#!/usr/bin/env node
/**
 * Webflow Designer styles → one CSS file.
 * Reusable for any Webflow migration.
 *
 * Inputs (all from the Webflow Data API via the Webflow MCP connector):
 *   migration/webflow-styles.json     data_style_tool > get_styles (query: all, include_properties, all breakpoints/pseudos)
 *   migration/webflow-variables.json  variables + fonts
 *   migration/webflow-assets.json     asset id → url (for background images)
 *   migration/webflow-variant-styles.json  (optional) component variant overrides
 *
 * Output: src/styles/webflow.css
 *
 * Usage: node scripts/webflow-styles-to-css.mjs
 */
import fs from 'node:fs'

const read = (f) => JSON.parse(fs.readFileSync(f, 'utf8'))
const styles = read('migration/webflow-styles.json').result
const {variables, fonts} = read('migration/webflow-variables.json')
const assets = read('migration/webflow-assets.json')
const variantFile = 'migration/webflow-variant-styles.json'
const variantStyles = fs.existsSync(variantFile) ? read(variantFile).styles : []

const varById = Object.fromEntries(variables.map((v) => [v.id, v.cssName]))

/** Webflow breakpoints. Desktop-first; large/xl/xxl are min-width additions. */
const BREAKPOINTS = [
  ['main', null],
  ['large', '(min-width: 1280px)'],
  ['xl', '(min-width: 1440px)'],
  ['xxl', '(min-width: 1920px)'],
  ['medium', '(max-width: 991px)'],
  ['small', '(max-width: 767px)'],
  ['tiny', '(max-width: 479px)'],
]

const PSEUDO = {
  noPseudo: '',
  hover: ':hover',
  active: ':active',
  focus: ':focus',
  'focus-visible': ':focus-visible',
  'focus-within': ':focus-within',
  visited: ':visited',
  placeholder: '::placeholder',
  before: '::before',
  after: '::after',
  empty: ':empty',
  'first-child': ':first-child',
  'last-child': ':last-child',
  'nth-child(odd)': ':nth-child(odd)',
  'nth-child(even)': ':nth-child(even)',
}

const missing = new Set()
function value(v) {
  if (v && typeof v === 'object' && typeof v.id === 'string') {
    const name = varById[v.id]
    if (!name) missing.add(v.id)
    return name ? `var(${name})` : 'initial'
  }
  if (typeof v !== 'string') return String(v)
  return v.replace(/@img_([0-9a-f]{24})/g, (_, id) => {
    const url = assets[id]?.url
    if (!url) missing.add(id)
    return url ? `url("${url}")` : 'none'
  })
}

const block = (selector, props) => {
  const lines = Object.entries(props).map(([k, v]) => `  ${k}: ${value(v)};`)
  return lines.length ? `${selector} {\n${lines.join('\n')}\n}` : ''
}

/** Pseudo applies to the last compound selector: ".a .b" + ":hover" → ".a .b:hover" */
const withPseudo = (selector, pseudo) =>
  selector
    .split(',')
    .map((s) => s.trim() + PSEUDO[pseudo])
    .join(', ')

const buckets = Object.fromEntries(BREAKPOINTS.map(([bp]) => [bp, []]))

// Tag styles first, then global classes, then combos — same cascade order Webflow publishes
const order = {tag: 0, global: 1, combo: 2}
const sorted = [...styles].sort((a, b) => order[a.type] - order[b.type])

for (const style of sorted) {
  const bps = style.properties.breakpoints ?? {main: style.properties.base}
  for (const [bp] of BREAKPOINTS) {
    const data = bps[bp]
    if (!data) continue
    const pseudos = data.pseudos ?? {noPseudo: data.properties ?? {}}
    for (const [pseudo, props] of Object.entries(pseudos)) {
      if (!(pseudo in PSEUDO)) continue
      const css = block(withPseudo(style.selector, pseudo), props)
      if (css) buckets[bp].push(css)
    }
  }
}

// Component variant overrides: rendered as `.variant-<slug>` modifier on the component root
for (const v of variantStyles) {
  const bp = v.breakpoint ?? 'main'
  const css = block(withPseudo(v.selector, v.pseudo ?? 'noPseudo'), v.properties)
  if (css) buckets[bp].push(css)
}

const out = []
out.push(`/* GENERATED by scripts/webflow-styles-to-css.mjs from the Webflow export — do not edit by hand.
   Put overrides and new styles in src/styles/site.css instead. */`)

for (const f of fonts) {
  out.push(`@font-face {
  font-family: '${f.family}';
  src: url('${f.url}') format('${f.format}');
  font-weight: ${f.weight};
  font-style: ${f.style};
  font-display: swap;
}`)
}

const rootVars = variables.map((v) => `  ${v.cssName}: ${v.base};`).join('\n')
out.push(`:root {\n${rootVars}\n}`)
for (const [mode, query] of [
  ['medium', '(max-width: 991px)'],
  ['small', '(max-width: 767px)'],
]) {
  const vs = variables.filter((v) => v[mode] && v[mode] !== v.base)
  if (vs.length) out.push(`@media ${query} {\n  :root {\n${vs.map((v) => `    ${v.cssName}: ${v[mode]};`).join('\n')}\n  }\n}`)
}

for (const [bp, query] of BREAKPOINTS) {
  const rules = buckets[bp]
  if (!rules.length) continue
  out.push(`/* ---- ${bp} ---- */`)
  if (!query) out.push(rules.join('\n'))
  else out.push(`@media ${query} {\n${rules.map((r) => r.replace(/^/gm, '  ')).join('\n')}\n}`)
}

fs.mkdirSync('src/styles', {recursive: true})
fs.writeFileSync('src/styles/webflow.css', out.join('\n\n') + '\n')
const count = Object.values(buckets).reduce((n, r) => n + r.length, 0)
console.log(`src/styles/webflow.css: ${count} rules from ${styles.length} styles${variantStyles.length ? ` + ${variantStyles.length} variant overrides` : ''}`)
if (missing.size) console.warn(`  ! unresolved variables/assets: ${[...missing].join(', ')}`)
